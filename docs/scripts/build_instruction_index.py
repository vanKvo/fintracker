#!/usr/bin/env python3
"""Build docs/INSTRUCTIONS.md, the index of every instruction file, grouped by topic.

Usage (from anywhere):
    python3 docs/scripts/build_instruction_index.py           # rewrite docs/INSTRUCTIONS.md
    python3 docs/scripts/build_instruction_index.py --check   # exit 1 if the index is stale or a file is not in CATEGORIES

Every regular file in docs/instructions/ is an instruction. Add a new file by adding
one line to CATEGORIES below, then re-run the script. The file itself is not edited.
Standard library only.
"""
import os
import sys

DOCS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FOLDER = os.path.join(DOCS, "instructions")
OUT = os.path.join(DOCS, "INSTRUCTIONS.md")

# Topic order is the order of the index. Each file belongs to exactly one topic.
CATEGORIES = [
    ("Local setup", [
        "setup_jdk_for_maven.md",
        "setup_postgresql16_homebrew.md",
        "connect_ledger_to_shared_postgres.md",
        "setup_local_dynamodb.md",
        "setup_local_s3.md",
        "configure_aws_dev_profile.md",
        "check_active_profile.md",
    ]),
    ("Build and run", [
        "rebuild_ledger_container_and_migrations.md",
        "knowledge_service_build_test_deploy.md",
        "knowledge_rag_live_evaluation.md",
        "useful_commands.md",
    ]),
    ("Local users and identity", [
        "cognito_ledger_test_setup.md",
        "connect_dev_user_to_Cognito_user",
        "dev_setup_user.py_create_new_user.md",
        "sam_user_profile_identity_local_lambda_api_gateway.md",
    ]),
    ("Deployment and runbooks", [
        "deploy_dp_ledger_categories.md",
        "deploy_import_reliability.md",
        "xs_acct_04_account_number_purge_runbook.md",
        "xs_comp_03_04_05_identity_controls_runbook.md",
    ]),
    ("Development practice", [
        "writing_java_tests.md",
        "build_new_spec_in_SPEC.md",
    ]),
    ("Troubleshooting and background", [
        "debugging_tips.md",
        "explanation_clock_vs_monotic.md",
    ]),
]

# Short titles for files whose first heading is missing or is not a usable name.
TITLES = {
    "setup_jdk_for_maven.md": "Use JDK 21 for Maven",
    "check_active_profile.md": "Check which .env values the Ledger loads",
    "useful_commands.md": "Useful commands (tests, container, image checks)",
    "connect_dev_user_to_Cognito_user": "Link a dev Cognito account to the local Ledger",
    "dev_setup_user.py_create_new_user.md": "Create or link the dev user (dev_setup_user.py)",
    "sam_user_profile_identity_local_lambda_api_gateway.md": "Run User profile identity locally (SAM)",
    "build_new_spec_in_SPEC.md": "Add a new spec to SPECS.md",
    "debugging_tips.md": "Find the real cause in a Spring bean-wiring failure",
    "explanation_clock_vs_monotic.md": "Why service.py uses two time sources",
    "knowledge_rag_live_evaluation.md": "Run the live RAG evaluation (paid, owner only)",
}

SUMMARY_MAX = 180


def instruction_files():
    return sorted(
        f for f in os.listdir(FOLDER)
        if os.path.isfile(os.path.join(FOLDER, f))
    )


def title_and_summary(path):
    """Title is the TITLES override, else the first '# ' heading, else the file name. Summary is the
    first paragraph under '## Description', else the first plain line."""
    lines = open(path, encoding="utf-8").read().splitlines()
    title = os.path.basename(path)
    for line in lines:
        if line.startswith("# "):
            title = line[2:].strip()
            break
    title = TITLES.get(os.path.basename(path), title)

    summary = ""
    in_description = False
    for line in lines:
        stripped = line.strip()
        if stripped.lower() == "## description":
            in_description = True
            continue
        if in_description and stripped.startswith("#"):
            break
        if in_description and stripped:
            summary = stripped
            break
    if not summary:
        for line in lines:
            stripped = line.strip()
            if stripped and not stripped.startswith("#"):
                summary = stripped
                break

    summary = " ".join(summary.replace("|", "\\|").split())
    if len(summary) > SUMMARY_MAX:
        summary = summary[:SUMMARY_MAX].rsplit(" ", 1)[0] + "…"
    return " ".join(title.replace("|", "\\|").split()), summary


def problems(files):
    """Files not listed in CATEGORIES, and CATEGORIES entries that no longer exist."""
    listed = [name for _, names in CATEGORIES for name in names]
    missing = [f for f in files if f not in listed]
    stale = [n for n in listed if n not in files]
    duplicated = sorted({n for n in listed if listed.count(n) > 1})
    return missing, stale, duplicated


def build(files):
    out = [
        "# Instruction Index",
        "",
        "Generated by `python3 docs/scripts/build_instruction_index.py`. Do not edit by hand; "
        "edit the topic list in that script and re-run it.",
        "",
        "Each entry links to the instruction file. The summary comes from the file's Description section.",
        "",
    ]
    for topic, names in CATEGORIES:
        out += [f"## {topic}", "", "| Instruction | What it covers |", "|---|---|"]
        for name in names:
            title, summary = title_and_summary(os.path.join(FOLDER, name))
            out.append(f"| [{title}](instructions/{name}) | {summary} |")
        out.append("")
    return "\n".join(out)


def main():
    files = instruction_files()
    missing, stale, duplicated = problems(files)
    check = "--check" in sys.argv

    if missing or stale or duplicated:
        for f in missing:
            print(f"Not in CATEGORIES: {f}")
        for f in stale:
            print(f"In CATEGORIES but no such file: {f}")
        for f in duplicated:
            print(f"Listed under more than one topic: {f}")
        sys.exit(1)

    text = build(files)
    if check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            print("INSTRUCTIONS.md is stale: run python3 docs/scripts/build_instruction_index.py")
            sys.exit(1)
        print("INSTRUCTIONS.md is up to date.")
        return

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"Wrote {OUT} ({len(files)} instructions).")


if __name__ == "__main__":
    main()
